#!/usr/bin/env bash
# Concatenates every migration (in order) into one file you can paste into Supabase → SQL Editor.
# Re-run after adding a migration: supabase/setup/build.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/all-migrations.sql"
{
  echo "-- Twofold: every database migration in one file, generated by supabase/setup/build.sh."
  echo "-- Paste into Supabase → SQL Editor → New query → Run, on a NEW project (run it once)."
  for f in "$here"/../migrations/*.sql; do
    echo
    echo "-- ======================================================================"
    echo "-- $(basename "$f")"
    echo "-- ======================================================================"
    cat "$f"
  done
} > "$out"
echo "Wrote $out"
